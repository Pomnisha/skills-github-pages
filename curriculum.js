// Допоміжна функція для генерації testId
function makeTestId(subjectId, themeId, conceptId, level) {
  return subjectId + "-t" + themeId + "-c-" + conceptId + "-" + level;
}

// Підрахунок усіх тестів
function countAllTests() {
  let total = 0;
  CURRICULUM.subjects.forEach(function(s) {
    s.themes.forEach(function(t) {
      total += t.concepts.length * 3;
    });
  });
  return total;
}

